const REGISTER = (pattern) => /において|につき|に基づ|をもって|を禁じ|たる|べく|に則|に即|に照ら|相まって|の至り|の極み|を顧み/.test(pattern) ? '正式／书面' : /くせに|っぱなし|なんて|ものか/.test(pattern) ? '口语／带态度' : '中性／通用';

function makePoint([module, pattern, meaning, connection, zhA, jaA, zhB, jaB], order) {
  const explanation = `${MODULE_HINTS[module]}。${pattern}的核心是“${meaning}”，实际使用时要先确认接续，再判断说话人的语气。`;
  const pitfalls = `不要只按中文直译；特别注意${pattern}前面的接续形式，以及它和相近表达在语气、范围或时间关系上的差别。`;
  const related = `可与同模块表达一起辨析：${module}中的相近句型；先看前项接续，再看后项结论。`;
  const keywords = [pattern, meaning, module, connection, 'JLPT N2'];
  const point = {
    id: `n2-${String(order).padStart(3, '0')}`,
    order,
    module,
    pattern,
    kana: pattern.replace(/[（）]/g, ''),
    meaning,
    usage: MODULE_HINTS[module],
    connection,
    explanation,
    examples: [
      { ja: jaA, zh: zhA },
      { ja: jaB, zh: zhB },
    ],
    pitfalls,
    related,
    register: REGISTER(pattern),
    keywords,
  };
  point.questions = buildQuestions(point, RAW_POINTS);
  return point;
}

